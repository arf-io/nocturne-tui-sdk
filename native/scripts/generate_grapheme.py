#!/usr/bin/env python3
"""Offline Unicode 17 table generator; inputs verified against pinned source hashes."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
NAMES=['Other','CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT']
def generate():
    folder=ROOT/'unicode/17.0.0';manifest=json.loads((folder/'SOURCES.json').read_text())
    for row in manifest['sources']:
        if hashlib.sha256((folder/row['name']).read_bytes()).hexdigest()!=row['sha256']:raise ValueError('Unicode source hash mismatch: '+row['name'])
    flags=bytearray(0x110000)
    for name in ('GraphemeBreakProperty.txt','emoji-data.txt','DerivedCoreProperties.txt'):
        for line in (folder/name).read_text().splitlines():
            fields=[p.strip() for p in line.split('#')[0].split(';')]
            if len(fields)<2:continue
            if name=='GraphemeBreakProperty.txt':value=NAMES.index(fields[1]);mask=15
            elif name=='emoji-data.txt':
                if fields[1]!='Extended_Pictographic':continue
                value=16;mask=16
            else:
                if fields[1]!='InCB':continue
                value={'Consonant':1,'Extend':2,'Linker':3}[fields[2]]<<5;mask=96
            span=fields[0].split('..');a=int(span[0],16);b=int(span[-1],16)
            for i in range(a,b+1):flags[i]=(flags[i]&~mask)|value
    ranges=[];start=0
    for i in range(1,len(flags)+1):
        if i==len(flags) or flags[i]!=flags[start]:
            if flags[start]:ranges.append((start,i-1,flags[start]))
            start=i
    head='/* Generated by scripts/generate_grapheme.py from pinned Unicode 17.0.0.\n * Unicode data license: unicode/17.0.0/LICENSE.txt. Do not edit by hand.\n * Low 4 bits: GCB; bit 4: Extended_Pictographic; bits 5..6: InCB. */\n'
    return head+'static const UnicodeRange unicodeRanges[]={\n'+''.join(f'    {{0x{a:x}u,0x{b:x}u,{v}u}},\n' for a,b,v in ranges)+'};\n',len(ranges)
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();data,count=generate();out=ROOT/'src/unicode_grapheme.inc'
    if args.check:
        if out.read_text()!=data:raise SystemExit('Generated Unicode table differs')
    else:out.write_text(data)
    print(f'Unicode 17.0.0: {count} compact property ranges')
