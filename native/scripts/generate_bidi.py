#!/usr/bin/env python3
"""Offline Unicode 17 bidi property tables with verified pinned source hashes."""
import argparse,hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
NAMES='L R AL EN AN ES ET CS NSM BN B S WS ON LRE LRO RLE RLO PDF LRI RLI FSI PDI'.split()
LONG=dict(zip('Left_To_Right Right_To_Left Arabic_Letter European_Number Arabic_Number European_Separator European_Terminator Common_Separator Nonspacing_Mark Boundary_Neutral Paragraph_Separator Segment_Separator White_Space Other_Neutral Left_To_Right_Embedding Left_To_Right_Override Right_To_Left_Embedding Right_To_Left_Override Pop_Directional_Format Left_To_Right_Isolate Right_To_Left_Isolate First_Strong_Isolate Pop_Directional_Isolate'.split(),NAMES))
def span(text):
 parts=text.split('..');return int(parts[0],16),int(parts[-1],16)
def generate():
 folder=ROOT/'unicode/17.0.0';manifest=json.loads((folder/'SOURCES.json').read_text())
 for row in manifest['sources']:
  if hashlib.sha256((folder/row['name']).read_bytes()).hexdigest()!=row['sha256']:raise ValueError('Unicode source hash mismatch: '+row['name'])
 classes=bytearray(0x110000);lines=(folder/'DerivedBidiClass.txt').read_text().splitlines()
 for line in lines:
  if '@missing:' in line:
   interval,name=line.split('@missing:')[1].strip().split(';');a,b=span(interval.strip());v=NAMES.index(LONG[name.strip()]);classes[a:b+1]=bytes([v])*(b-a+1)
 for line in lines:
  fields=[p.strip() for p in line.split('#')[0].split(';')]
  if len(fields)<2:continue
  a,b=span(fields[0]);v=NAMES.index(fields[1]);classes[a:b+1]=bytes([v])*(b-a+1)
 ranges=[];start=0
 for i in range(1,len(classes)+1):
  if i==len(classes) or classes[i]!=classes[start]:
   if classes[start]:ranges.append((start,i-1,classes[start]))
   start=i
 data='/* Generated by generate_bidi.py; Unicode 17.0.0, Unicode data license. */\n'
 data+='static const BidiRange bidiRanges[]={\n'+''.join(f' {{0x{a:x}u,0x{b:x}u,{v}u}},\n' for a,b,v in ranges)+'};\n'
 for file,table in [('BidiBrackets.txt','bidiBrackets'),('BidiMirroring.txt','bidiMirrors')]:
  rows=[]
  for line in (folder/file).read_text().splitlines():
   fields=[p.strip() for p in line.split('#')[0].split(';')]
   if len(fields)<2:continue
   a,b=int(fields[0],16),int(fields[1],16);v={'o':1,'c':2}[fields[2]] if len(fields)>2 else 0;rows.append((a,b,v))
  rows.sort();data+=f'static const BidiPair {table}[]={{\n'+''.join(f' {{0x{a:x}u,0x{b:x}u,{v}u}},\n' for a,b,v in rows)+'};\n'
 return data
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();data=generate();out=ROOT/'src/unicode_bidi.inc'
 if args.check:
  if out.read_text()!=data:raise SystemExit('Generated bidi table differs')
 else:out.write_text(data)
 print('Unicode 17 bidi direction/bracket/mirror tables verified')
