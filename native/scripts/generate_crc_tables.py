#!/usr/bin/env python3
"""Regenerate immutable slicing-by-eight IEEE CRC32 tables."""
from pathlib import Path

def tables():
    first=[]
    for byte in range(256):
        value=byte
        for _ in range(8):
            value=(value >> 1) ^ (0xedb88320 if value & 1 else 0)
        first.append(value)
    result=[first]
    for _ in range(7):
        result.append([(value >> 8) ^ first[value & 255] for value in result[-1]])
    return result

def render():
    lines=['/* Generated by scripts/generate_crc_tables.py; reflected IEEE 0xedb88320. */',
           'static const uint32_t nrCrcTables[8][256]={']
    for table in tables():
        lines.append('    {')
        for start in range(0,256,8):
            lines.append('        '+','.join(f'0x{value:08x}u' for value in table[start:start+8])+',')
        lines.append('    },')
    return '\n'.join(lines+['};',''])

if __name__=='__main__':
    Path(__file__).resolve().parents[1].joinpath('src/crc_tables.h').write_text(render())
