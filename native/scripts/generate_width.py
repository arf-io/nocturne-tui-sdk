#!/usr/bin/env python3
"""Offline pinned Unicode 17 properties for Nocturne's explicit cell-width profile."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate():
    folder=ROOT/'unicode/17.0.0'
    for row in json.loads((folder/'SOURCES.json').read_text())['sources']:
        if hashlib.sha256((folder/row['name']).read_bytes()).hexdigest()!=row['sha256']:raise ValueError('Unicode source hash mismatch: '+row['name'])
    flags=bytearray(0x110000)
    for name in ('EastAsianWidth.txt','emoji-data.txt','DerivedCoreProperties.txt'):
        for line in (folder/name).read_text().splitlines():
            fields=[p.strip() for p in line.split('#')[0].split(';')]
            if len(fields)<2:continue
            if name=='EastAsianWidth.txt':v=1 if fields[1] in ('W','F') else 2 if fields[1]=='A' else 0
            elif name=='emoji-data.txt':v=8 if fields[1]=='Emoji_Presentation' else 0
            else:v=4 if fields[1]=='Default_Ignorable_Code_Point' else 0
            span=fields[0].split('..');a=int(span[0],16);b=int(span[-1],16)
            if v:
                for i in range(a,b+1):flags[i]|=v
    start=None
    for line in (folder/'UnicodeData.txt').read_text().splitlines():
        f=line.split(';');cp=int(f[0],16)
        if f[1].endswith(', First>'):start=cp;continue
        first=start if f[1].endswith(', Last>') else cp;start=None
        if f[2] in ('Mn','Me','Cf','Cc','Zl','Zp'):
            for i in range(first,cp+1):flags[i]|=4
    for line in (folder/'emoji-variation-sequences.txt').read_text().splitlines():
        f=line.split('#')[0].split(';')
        if len(f)>1:flags[int(f[0].split()[0],16)]|=16
    ranges=[];start=0
    for i in range(1,len(flags)+1):
        if i==len(flags) or flags[i]!=flags[start]:
            if flags[start]:ranges.append((start,i-1,flags[start]))
            start=i
    header='/* Generated by scripts/generate_width.py; Unicode 17.0.0.\n * License: unicode/17.0.0/LICENSE.txt. Bits: wide=1, ambiguous=2,\n * zero=4, Emoji_Presentation=8, standardized emoji variation base=16. */\n'
    return header+'static const WidthRange widthRanges[]={\n'+''.join(f'    {{0x{a:x}u,0x{b:x}u,{v}u}},\n' for a,b,v in ranges)+'};\n',len(ranges)
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();data,count=generate();out=ROOT/'src/unicode_width.inc'
    if args.check:
        if out.read_text()!=data:raise SystemExit('Generated width table differs')
    else:out.write_text(data)
    print(f'Unicode 17.0.0: {count} compact width property ranges')
