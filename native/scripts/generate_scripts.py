#!/usr/bin/env python3
"""Generate deterministic native Unicode-17 script/extension tables from UCD."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1];DATA=ROOT/'unicode/17.0.0'
def lines(name):
 for line in (DATA/name).read_text().splitlines():
  line=line.split('#',1)[0].strip()
  if line:yield [part.strip() for part in line.split(';')]
def bounds(value):
 parts=value.split('..');return int(parts[0],16),int(parts[-1],16)
def generate():
 receipt=json.loads((DATA/'SOURCES.json').read_text());sources={item['name']:item for item in receipt['sources']}
 for name in ['Scripts.txt','ScriptExtensions.txt','PropertyValueAliases.txt']:
  data=(DATA/name).read_bytes();source=sources[name]
  if len(data)!=source['bytes'] or hashlib.sha256(data).hexdigest()!=source['sha256']:raise ValueError('Source digest mismatch: '+name)
 aliases={}
 for fields in lines('PropertyValueAliases.txt'):
  if fields[0]=='sc':
   for alias in fields[1:]:aliases[alias]=fields[1]
 tags=sorted(set(aliases.values()));identities={tag:i for i,tag in enumerate(tags)}
 if len(tags)>256:raise ValueError('Native script mask capacity exceeded')
 scripts=sorted((*bounds(fields[0]),identities[aliases[fields[1]]]) for fields in lines('Scripts.txt'))
 extensions=[]
 for fields in lines('ScriptExtensions.txt'):
  mask=[0]*4
  for alias in fields[1].split():
   i=identities[aliases[alias]];mask[i//64]|=1<<(i%64)
  extensions.append((*bounds(fields[0]),mask))
 extensions.sort()
 for ranges in [scripts,extensions]:
  previous=-1
  for row in ranges:
   if row[0]<=previous or row[0]>row[1] or row[1]>0x10ffff:raise ValueError('Invalid Unicode script interval')
   previous=row[1]
 output=['/* Generated by generate_scripts.py; Unicode 17.0.0 UCD hashes in SOURCES.json. */',
  f'#define NR_SCRIPT_COUNT {len(tags)}',f'#define NR_SCRIPT_COMMON {identities["Zyyy"]}',f'#define NR_SCRIPT_INHERITED {identities["Zinh"]}',f'#define NR_SCRIPT_UNKNOWN {identities["Zzzz"]}',
  'static const uint32_t scriptTags[]={'+','.join(f'0x{int.from_bytes(tag.encode(),"big"):08x}u' for tag in tags)+'};',
  'static const struct {uint32_t first,last;uint16_t script;} scriptRanges[]={']
 output += [f'{{0x{a:x},0x{b:x},{script}}},' for a,b,script in scripts];output+=['};','static const struct {uint32_t first,last;uint64_t mask[4];} scriptExtensions[]={']
 output += ['{0x%x,0x%x,{%s}},'%(a,b,','.join('0x%xull'%word for word in mask)) for a,b,mask in extensions];output+=['};','']
 (ROOT/'src/unicode_scripts.inc').write_text('\n'.join(output))
if __name__=='__main__':generate()
